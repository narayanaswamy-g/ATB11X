package ex_07_IncrementDecrementOperators;

public class Lab70_IncrementDecrementOperators {
    static void main() {
        int a=10;
        //PRE-INCREMENT
        System.out.println(++a);
        System.out.println(a);
        //POST INCREMENT
        int b=20;
        System.out.println(b++);
        System.out.println(b);
    }
}

package ex_02_Java_Basic_Part2;

public class Lab16_printF {
    public static void main(String[] args) {
        int a = 10;

        System.out.printf("Integer value of a is %d%n", a);
        System.out.printf("Float value of a is %.2f%n", (float) a);
        System.out.printf("Boolean value of a is %b%n", a);
    }
}
